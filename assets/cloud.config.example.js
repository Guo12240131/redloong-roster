/* ============================================================
   cloud.config.example.js — 云端同步配置「模板」
   ------------------------------------------------------------
   用法：
     1. 把本文件复制一份，改名为 cloud.config.js（同目录）
     2. 填上你自己的云项目 endpoint 与 publishableKey
     3. 刷新页面，锻造模式里的「云同步」就能登录了

   为什么仓库里不带 cloud.config.js：
     它是每个人各自的凭据，进版本库没有意义，也容易让别人的页面
     连到你的库上。所以 .gitignore 把它排除掉了。

   不建这个文件会怎样：
     页面照常打开，但同步层自动关闭 —— 也就是「离线单机版」，
     所有编辑只存在当前浏览器（可导出 JSON 带走）。

   ⚠ publishableKey 是设计上可公开的密钥（类似 Supabase 的 anon key），
     它本身不是秘密。真正的安全边界是云数据库的 RLS 行级策略 ——
     别指望靠藏这个 key 来保护数据，该配的策略一条都不能少。
   ============================================================ */
window.CLOUD_CONFIG = {
  /* 你的云服务地址（应用发布后的域名） */
  endpoint: 'https://your-app.example.com',

  /* 应用的 publishable key，形如 wbpk_xxxxxxxx_yyyyyyyy */
  publishableKey: 'wbpk_你的应用ID_你的密钥',

  /* 名册在云端的主键名。除非你要在一个项目里放多份名册，否则不用改 */
  rosterDoc: 'main'
};
